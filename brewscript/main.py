
from pathlib import Path

from brewscript_lexer import Lexer
from recursive_descent_parser import parse_tokens, ParserError


def display_tokens(tokens):
    print("\nTOKEN TABLE")
    print("=" * 78)
    print(f"{'Token Type':<22} {'Lexeme':<40} {'Line:Col':<12}")
    print("-" * 78)

    if tokens:
        for token in tokens:
            position = f"{token.line}:{token.col}"
            print(f"{token.type:<22} {token.lexeme!r:<40} {position:<12}")
    else:
        print("No tokens were generated.")

    print("-" * 78)
    print(f"Total tokens: {len(tokens)}")


def main():
    filename = input(
        "Enter BrewScript file name "
        "(for example, my_test.brew, valid_test.brew, syntax_error_test.brew): "
    ).strip()

    try:
        source = Path(filename).read_text(encoding="utf-8")
    except OSError as error:
        print(f"Could not read file: {error}")
        return

    # Stage 1: Lexical analysis
    lexer = Lexer(source)
    tokens, errors = lexer.tokenize()

    display_tokens(tokens)

    if errors:
        print("\nLEXICAL ERRORS")
        print("=" * 78)

        for number, error in enumerate(errors, start=1):
            print(f"{number}. {error}")

        print(f"\nTotal lexical errors: {len(errors)}")
        print("\nContinuing to parsing with the tokens generated by the lexer.")
        print("Note: lexical errors may affect the parsing result.")
    else:
        print("\nLexical analysis successful. No lexical errors found.")

    # Stage 2: Parsing using the same token list
    try:
        parse_tokens(tokens)
        print("\nPARSING SUCCESSFUL: The token sequence follows the CFG.")
    except ParserError as error:
        print(f"\nPARSING FAILED: {error}")


if __name__ == "__main__":
    main()
